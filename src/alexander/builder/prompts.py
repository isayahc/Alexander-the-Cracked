"""Pure prompt and README rendering for the builder (no I/O here)."""

from alexander.builder.models import HackathonBrief


def render_attempt_prompt(
    brief: HackathonBrief,
    attempt: int,
    max_attempts: int,
    failure_notes: str = "",
) -> str:
    """Render the instruction prompt for one build attempt."""
    themes = ", ".join(brief.themes) if brief.themes else "none listed"
    lines = [
        "You are Alexander, an autonomous hackathon project builder.",
        "",
        f"Event: {brief.event_name}",
        f"Themes: {themes}",
        f"Deadline: {brief.deadline or 'not stated'}",
        f"Prize: {brief.prize or 'not stated'}",
        "",
        f"What to build: {brief.description}",
        "",
        "Work inside the current directory and do all of the following, in order:",
        "1. Write SPEC.md: a short spec (what it does, how to run it, what you cut).",
        "2. Scaffold a minimal runnable project. Prefer Python with pytest; stick to the",
        "   standard library unless the idea truly needs more.",
        "3. Implement the core functionality described above.",
        "4. Write tests for the core behaviour and run them (e.g. python -m pytest) until",
        "   they pass.",
        "5. Write README.md: a one-page pitch (what it is, why it wins, how to run it).",
        "",
        f"This is attempt {attempt} of {max_attempts}. Keep it small: a working, tested toy",
        "beats a broken giant.",
    ]
    if failure_notes:
        lines += [
            "",
            f"Feedback from the previous attempt: {failure_notes}",
            "Fix these problems first, then rerun the tests.",
        ]
    return "\n".join(lines)


def render_fallback_readme(brief: HackathonBrief, test_summary: str) -> str:
    """Render a minimal README/pitch for a successful build the agent left without one."""
    themes = ", ".join(brief.themes) if brief.themes else "no listed themes"
    return (
        f"# {brief.event_name} build\n"
        "\n"
        f"{brief.description}\n"
        "\n"
        "## Pitch\n"
        "\n"
        f"Built for {brief.event_name} ({themes}). See SPEC.md for scope and the source\n"
        "for details — this README was generated by Alexander after the tests passed.\n"
        "\n"
        "## Status\n"
        "\n"
        f"Tests: {test_summary}\n"
    )
